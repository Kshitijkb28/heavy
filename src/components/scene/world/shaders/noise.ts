/** Shared GLSL: a cheap 2-octave hash/value noise for the volumes (no textures). */
export const glslNoise = /* glsl */ `
float hash12(vec2 p) {
  vec3 p3 = fract(vec3(p.xyx) * 0.1031);
  p3 += dot(p3, p3.yzx + 33.33);
  return fract((p3.x + p3.y) * p3.z);
}
float vnoise(vec2 p) {
  vec2 i = floor(p);
  vec2 f = fract(p);
  f = f * f * (3.0 - 2.0 * f);
  float a = hash12(i);
  float b = hash12(i + vec2(1.0, 0.0));
  float c = hash12(i + vec2(0.0, 1.0));
  float d = hash12(i + vec2(1.0, 1.0));
  return mix(mix(a, b, f.x), mix(c, d, f.x), f.y);
}
float noise2(vec2 p) {
  return vnoise(p) * 0.667 + vnoise(p * 2.03 + 17.1) * 0.333;
}
`;

/** Multiplies an additive colour by (1 − fog) so volumes vanish into the black haze instead of tinting it. */
export const glslFogFade = /* glsl */ `
#ifdef USE_FOG
  #ifdef FOG_EXP2
    float fogFactor = 1.0 - exp(-fogDensity * fogDensity * vFogDepth * vFogDepth);
  #else
    float fogFactor = smoothstep(fogNear, fogFar, vFogDepth);
  #endif
  col *= 1.0 - fogFactor;
#endif
`;
